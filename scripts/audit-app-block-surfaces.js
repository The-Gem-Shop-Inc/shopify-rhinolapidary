const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const SECTION_DIR = path.join(ROOT, 'sections');
const TEMPLATE_DIR = path.join(ROOT, 'templates');
const OUTPUT = path.join(ROOT, 'docs/apps/app-block-surface-audit.md');

function readText(file) {
    return fs.readFileSync(file, 'utf8');
}

function normalize(filePath) {
    return filePath.split(path.sep).join('/');
}

function listFiles(dir, extensions) {
    if (!fs.existsSync(dir)) {
        return [];
    }

    const results = [];

    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const fullPath = path.join(dir, entry.name);

        if (entry.isDirectory()) {
            results.push(...listFiles(fullPath, extensions));
            continue;
        }

        if (extensions.has(path.extname(entry.name))) {
            results.push(fullPath);
        }
    }

    return results;
}

function extractSchema(liquid) {
    const match = liquid.match(/{%\s*schema\s*%}([\s\S]*?){%\s*endschema\s*%}/);

    if (!match) {
        return null;
    }

    try {
        return JSON.parse(match[1]);
    } catch (error) {
        return {
            parseError: error.message,
        };
    }
}

function sectionSupportsAppBlocks(sectionPath) {
    const content = readText(sectionPath);
    const schema = extractSchema(content);

    if (!schema || schema.parseError) {
        return {
            supportsApp: false,
            schema,
            blocks: [],
        };
    }

    const blocks = Array.isArray(schema.blocks) ? schema.blocks : [];
    const appBlocks = blocks.filter((block) => block && block.type === '@app');

    return {
        supportsApp: appBlocks.length > 0,
        schema,
        blocks: appBlocks,
    };
}

function sectionTypeFromTemplateSection(section) {
    if (typeof section === 'string') {
        return section;
    }

    if (section && typeof section.type === 'string') {
        return section.type;
    }

    return null;
}

function collectTemplateUsage() {
    const usage = new Map();
    const templateFiles = listFiles(TEMPLATE_DIR, new Set(['.json']));

    for (const templatePath of templateFiles) {
        const relativeTemplate = normalize(path.relative(ROOT, templatePath));
        let template;

        try {
            template = JSON.parse(readText(templatePath));
        } catch {
            continue;
        }

        const sections = template.sections || {};

        for (const [, section] of Object.entries(sections)) {
            const sectionType = sectionTypeFromTemplateSection(section);

            if (!sectionType) {
                continue;
            }

            if (!usage.has(sectionType)) {
                usage.set(sectionType, []);
            }

            usage.get(sectionType).push(relativeTemplate);
        }
    }

    return usage;
}

function riskForSection(sectionName) {
    if (/header|footer|cart|product|quick-order|main-product/i.test(sectionName)) {
        return 'High';
    }

    if (/featured|article|newsletter|apps|contact/i.test(sectionName)) {
        return 'Medium';
    }

    return 'Low';
}

const sectionFiles = listFiles(SECTION_DIR, new Set(['.liquid']));
const templateUsage = collectTemplateUsage();
const rows = [];

for (const sectionPath of sectionFiles) {
    const sectionName = path.basename(sectionPath, '.liquid');
    const relativeSection = normalize(path.relative(ROOT, sectionPath));
    const audit = sectionSupportsAppBlocks(sectionPath);

    if (!audit.supportsApp) {
        continue;
    }

    rows.push({
        section: relativeSection,
        sectionType: sectionName,
        templates: templateUsage.get(sectionName) || [],
        risk: riskForSection(sectionName),
    });
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });

const lines = [
    '# App Block Surface Audit',
    '',
    'Generated by `scripts/audit-app-block-surfaces.js`.',
    '',
    'This file maps theme sections that support Shopify `@app` blocks and identifies which JSON templates currently render those sections.',
    '',
    '| Section | Risk | Templates currently using section | Guidance |',
    '|---|:---:|---|---|',
];

for (const row of rows.sort((a, b) => a.section.localeCompare(b.section))) {
    const templates = row.templates.length > 0 ? row.templates.join('<br>') : 'Not currently used by JSON templates';
    const guidance =
        row.risk === 'High'
            ? 'Requires explicit review, preview testing, accessibility check, performance check, and rollback plan.'
            : 'Allowed only with owner, purpose, and release-note entry.';

    lines.push(`| \`${row.section}\` | ${row.risk} | ${templates} | ${guidance} |`);
}

if (rows.length === 0) {
    lines.push(`| None found | - | - | No app block surfaces detected. |`);
}

fs.writeFileSync(OUTPUT, `${lines.join('\n')}\n`, 'utf8');

console.log(`Wrote ${rows.length} app block surfaces to ${normalize(path.relative(ROOT, OUTPUT))}`);